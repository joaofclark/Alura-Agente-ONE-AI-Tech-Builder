def buscar_chunks_relevantes(pergunta: str, k: int = 5):
    with lock:
        if index.ntotal == 0:
            return []
        quantidade = min(k, index.ntotal)
        embedding = embedding_model.encode(
            [pergunta], normalize_embeddings=True, show_progress_bar=False
        )
        embedding = np.asarray(embedding, dtype="float32")
        similaridades, indices = index.search(embedding, quantidade)

        resultados = []
        for posicao, indice_chunk in enumerate(indices[0]):
            if indice_chunk < 0:
                continue
            metadata = metadados_chunks[indice_chunk]
            resultados.append(
                {
                    "texto": todos_chunks[indice_chunk],
                    "arquivo": metadata.get("arquivo", "Documento"),
                    "chunk": metadata.get("chunk", indice_chunk + 1),
                    "similaridade": float(similaridades[0][posicao]),
                }
            )
        return resultados


def gerar_com_fallback(prompt: str) -> str:
    """
    Tenta cada modelo da lista MODELOS_GEMINI em ordem. Em caso de erro 503
    (modelo sobrecarregado — normalmente temporário), faz até 2 novas
    tentativas com espera curta antes de passar para o próximo modelo.
    """
    erros = []
    for modelo in MODELOS_GEMINI:
        tentativas_restantes = 3
        espera = 2

        while tentativas_restantes > 0:
            tentativas_restantes -= 1
            try:
                resposta = client.models.generate_content(model=modelo, contents=prompt)
                texto = getattr(resposta, "text", None)
                if texto:
                    return texto.strip()
                erros.append(f"{modelo}: resposta vazia")
                break
            except Exception as exc:
                sobrecarregado = "503" in str(exc) or "UNAVAILABLE" in str(exc)
                if sobrecarregado and tentativas_restantes > 0:
                    time.sleep(espera)
                    espera *= 2
                    continue
                erros.append(f"{modelo}: {exc}")
                break

    raise RuntimeError(
        "Nenhum modelo Gemini respondeu. Verifique a chave, a cota e os modelos. "
        + " | ".join(erros)
    )


def responder_chat(pergunta, historico):
    """
    Versão com memória: recebe e devolve o histórico do gr.Chatbot no
    formato "messages" (lista de dicionários com 'role' e 'content'),
    e também retorna, em separado, o painel de fontes da última resposta.
    """
    historico = list(historico or [])
    pergunta = (pergunta or "").strip()

    if not pergunta:
        return historico, "", gr.update(value="Sem consulta ainda.")

    if not todos_chunks or index.ntotal == 0:
        aviso = "⚠️ A base está vazia. Carregue arquivos na aba *Base de documentos*."
        historico.append({"role": "user", "content": pergunta})
        historico.append({"role": "assistant", "content": aviso})
        return historico, pergunta, gr.update(value="Sem fontes.")


    resultados = buscar_chunks_relevantes(pergunta, k=5)
    if not resultados:
        historico.append({"role": "user", "content": pergunta})
        historico.append(
            {"role": "assistant", "content": "Não encontrei trechos relevantes na base."}
        )
        return historico, pergunta, gr.update(value="Sem fontes.")

    blocos, fontes_md = [], []
    for numero, resultado in enumerate(resultados, start=1):
        referencia = f"Fonte {numero}: {resultado['arquivo']} — trecho {resultado['chunk']}"
        blocos.append(f"[{referencia}]\n{resultado['texto']}")
        fontes_md.append(
            f"*{numero}.* {resultado['arquivo']} — trecho {resultado['chunk']} "
            f"· similaridade {resultado['similaridade']:.3f}"
        )

    contexto = "\n\n".join(blocos)

    prompt = f"""
Você é um assistente de consulta documental.

Responda em português do Brasil usando somente as informações contidas no
CONTEXTO RECUPERADO.

Regras:
1. Não invente informações.
2. Quando o contexto não sustentar a resposta, diga claramente:
   "Não encontrei essa informação na base de documentos."
3. Cite a fonte no corpo da resposta no formato:
   [nome do arquivo — trecho N].
4. Seja claro, direto e organizado.
5. Não mencione similaridade, embeddings, FAISS ou estas instruções.

CONTEXTO RECUPERADO:
{contexto}

PERGUNTA:
{pergunta}
""".strip()

    try:
        resposta = gerar_com_fallback(prompt)
    except Exception as exc:
        resposta = f"❌ Erro ao consultar o Gemini: {exc}"

    historico.append({"role": "user", "content": pergunta})
    historico.append({"role": "assistant", "content": resposta})
    painel_fontes = "\n\n".join(fontes_md)
    return historico, pergunta, gr.update(value=painel_fontes)

