def salvar_base():
    with lock:
        with open(CHUNKS_PATH, "wb") as arquivo:
            pickle.dump(todos_chunks, arquivo)
        METADADOS_PATH.write_text(
            json.dumps(metadados_chunks, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        faiss.write_index(index, str(INDEX_PATH))


def carregar_base():
    global todos_chunks, metadados_chunks, index
    with lock:
        todos_chunks = pickle.load(open(CHUNKS_PATH, "rb")) if CHUNKS_PATH.exists() else []
        metadados_chunks = (
            json.loads(METADADOS_PATH.read_text(encoding="utf-8"))
            if METADADOS_PATH.exists()
            else []
        )

        if len(metadados_chunks) != len(todos_chunks):
            metadados_chunks = [
                {"arquivo": "Documento sem metadados", "hash": "", "chunk": numero}
                for numero in range(len(todos_chunks))
            ]

        if INDEX_PATH.exists():
            index_carregado = faiss.read_index(str(INDEX_PATH))
            if index_carregado.ntotal == len(todos_chunks):
                index = index_carregado
                return

        reconstruir_indice(salvar=False)


def reconstruir_indice(salvar: bool = True):
    global index
    with lock:
        novo_indice = faiss.IndexFlatIP(DIMENSAO)
        if todos_chunks:
            embeddings = embedding_model.encode(
                todos_chunks, normalize_embeddings=True, show_progress_bar=False
            )
            embeddings = np.asarray(embeddings, dtype="float32")
            novo_indice.add(embeddings)
        index = novo_indice
        if salvar:
            salvar_base()


def hashes_existentes():
    return {item.get("hash") for item in metadados_chunks if item.get("hash")}


