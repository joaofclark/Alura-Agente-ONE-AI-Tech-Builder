def normalizar_lista_arquivos(arquivos):
    if arquivos is None:
        return []
    if isinstance(arquivos, (str, Path)):
        return [str(arquivos)]
    return [str(item) for item in arquivos]


def adicionar_documentos(arquivos):
    global todos_chunks, metadados_chunks

    caminhos = normalizar_lista_arquivos(arquivos)
    if not caminhos:
        return status_base("Nenhum arquivo selecionado."), listar_documentos()

    adicionados, ignorados, erros = [], [], []
    novos_chunks, novos_metadados = [], []
    hashes = hashes_existentes()

    for caminho in caminhos:
        nome = Path(caminho).name
        try:
            arquivo_hash = hash_arquivo(caminho)
            if arquivo_hash in hashes:
                ignorados.append(f"{nome} (já estava na base)")
                continue

            texto = extrair_texto(caminho)
            if not texto.strip():
                erros.append(f"{nome}: nenhum texto extraível")
                continue

            chunks = criar_chunks(texto)
            if not chunks:
                erros.append(f"{nome}: não gerou trechos")
                continue

            destino = ARQUIVOS_DIR / nome
            if destino.exists():
                destino = ARQUIVOS_DIR / f"{arquivo_hash[:8]}_{nome}"
            shutil.copy2(caminho, destino)

            for numero, chunk in enumerate(chunks, start=1):
                novos_chunks.append(chunk)
                novos_metadados.append(
                    {
                        "arquivo": nome,
                        "caminho_salvo": str(destino),
                        "hash": arquivo_hash,
                        "chunk": numero,
                    }
                )

            hashes.add(arquivo_hash)
            adicionados.append(f"{nome} ({len(chunks)} trechos)")

        except Exception as exc:
            erros.append(f"{nome}: {exc}")

    if novos_chunks:
        with lock:
            todos_chunks.extend(novos_chunks)
            metadados_chunks.extend(novos_metadados)
            embeddings = embedding_model.encode(
                novos_chunks, normalize_embeddings=True, show_progress_bar=False
            )
            embeddings = np.asarray(embeddings, dtype="float32")
            index.add(embeddings)
            salvar_base()

    mensagens = []
    if adicionados:
        mensagens.append("✅ Adicionados: " + "; ".join(adicionados))
    if ignorados:
        mensagens.append("ℹ️ Ignorados: " + "; ".join(ignorados))
    if erros:
        mensagens.append("⚠️ Problemas: " + "; ".join(erros))

    return status_base("\n".join(mensagens)), listar_documentos()


def remover_documento(nome_arquivo):
    """Remove um documento específico (e seus trechos) da base, pelo nome."""
    global todos_chunks, metadados_chunks

    if not nome_arquivo:
        return status_base("Selecione um documento para remover."), listar_documentos()

    with lock:
        indices_manter = [
            i for i, meta in enumerate(metadados_chunks) if meta.get("arquivo") != nome_arquivo
        ]

        if len(indices_manter) == len(metadados_chunks):
            return status_base(f"Documento '{nome_arquivo}' não encontrado."), listar_documentos()

        todos_chunks = [todos_chunks[i] for i in indices_manter]
        metadados_chunks = [metadados_chunks[i] for i in indices_manter]

        caminho_salvo = None
        for meta in metadados_chunks:
            pass  # metadados já filtrados; caminho do arquivo original é buscado abaixo

        # Apaga o arquivo físico salvo em ARQUIVOS_DIR, se existir.
        for arquivo in ARQUIVOS_DIR.glob("*"):
            if arquivo.name == nome_arquivo or arquivo.name.endswith(f"_{nome_arquivo}"):
                arquivo.unlink(missing_ok=True)

        reconstruir_indice(salvar=True)

    return status_base(f"🗑️ Documento removido: {nome_arquivo}"), listar_documentos()


def listar_documentos():
    nomes, vistos = [], set()
    for item in metadados_chunks:
        nome = item.get("arquivo", "Sem nome")
        if nome not in vistos:
            vistos.add(nome)
            nomes.append(nome)
    return gr.update(choices=nomes, value=None)


def status_base(mensagem: str = ""):
    documentos = []
    vistos = set()
    for item in metadados_chunks:
        nome = item.get("arquivo", "Sem nome")
        if nome not in vistos:
            vistos.add(nome)
            documentos.append(nome)

    cabecalho = (
        f"*Base ativa:* {len(documentos)} documento(s), "
        f"{len(todos_chunks)} trecho(s) e {index.ntotal} vetor(es)."
    )
    lista = "\n".join(f"- {nome}" for nome in documentos) or "- Nenhum documento carregado."

    partes = [cabecalho, lista]
    if mensagem:
        partes.insert(0, mensagem)
    return "\n\n".join(partes)


def resolver_pasta_drive(pasta_informada: str = "") -> Path:
    valor = (pasta_informada or "").strip()
    if not valor:
        return PASTA_DOCUMENTOS_DRIVE
    pasta = Path(valor)
    if not pasta.is_absolute():
        pasta = Path("/content/drive/MyDrive") / pasta
    return pasta


def localizar_arquivos_na_pasta(pasta: Path):
    extensoes = {".pdf", ".txt", ".md", ".docx"}
    if not pasta.exists():
        return []
    return sorted(
        str(c) for c in pasta.rglob("*") if c.is_file() and c.suffix.lower() in extensoes
    )


def importar_pasta_drive(pasta_informada: str = ""):
    pasta = resolver_pasta_drive(pasta_informada)
    if not pasta.exists():
        return status_base(f"⚠️ A pasta não foi encontrada: {pasta}"), listar_documentos()

    arquivos = localizar_arquivos_na_pasta(pasta)
    if not arquivos:
        return (
            status_base(f"⚠️ Nenhum PDF, TXT, MD ou DOCX foi encontrado em {pasta}."),
            listar_documentos(),
        )

    resultado, _ = adicionar_documentos(arquivos)
    texto = f"📂 Pasta consultada: {pasta}\n\n🔎 {len(arquivos)} arquivo(s) localizado(s).\n\n{resultado}"
    return texto, listar_documentos()


def importar_pasta_padrao_automaticamente():
    arquivos = localizar_arquivos_na_pasta(PASTA_DOCUMENTOS_DRIVE)
    if arquivos:
        texto, _ = importar_pasta_drive(str(PASTA_DOCUMENTOS_DRIVE))
        return texto
    return status_base(
        f"ℹ️ Pasta padrão pronta: {PASTA_DOCUMENTOS_DRIVE}. "
        "Coloque os documentos nela e clique em *Importar pasta do Drive*."
    )


