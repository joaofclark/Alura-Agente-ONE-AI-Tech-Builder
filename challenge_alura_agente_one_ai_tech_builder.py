def hash_arquivo(caminho: str) -> str:
    sha = hashlib.sha256()
    with open(caminho, "rb") as arquivo:
        for bloco in iter(lambda: arquivo.read(1024 * 1024), b""):
            sha.update(bloco)
    return sha.hexdigest()


def extrair_texto(caminho: str) -> str:
    caminho_obj = Path(caminho)
    extensao = caminho_obj.suffix.lower()

    if extensao == ".pdf":
        leitor = PdfReader(str(caminho_obj))
        partes = []
        for numero, pagina in enumerate(leitor.pages, start=1):
            texto = pagina.extract_text() or ""
            if texto.strip():
                partes.append(f"[Página {numero}]\n{texto}")
        return "\n\n".join(partes)

    if extensao in {".txt", ".md"}:
        for encoding in ("utf-8", "latin-1"):
            try:
                return caminho_obj.read_text(encoding=encoding)
            except UnicodeDecodeError:
                continue
        raise ValueError(f"Não foi possível identificar a codificação de {caminho_obj.name}.")

    if extensao == ".docx":
        documento = Document(str(caminho_obj))
        return "\n".join(
            paragrafo.text for paragrafo in documento.paragraphs if paragrafo.text.strip()
        )

    raise ValueError(f"Formato não suportado: {extensao}. Use PDF, TXT, MD ou DOCX.")


def criar_chunks(texto: str, tamanho: int = 450, sobreposicao: int = 80):
    palavras = texto.split()
    if not palavras:
        return []
    passo = max(1, tamanho - sobreposicao)
    return [
        " ".join(palavras[inicio:inicio + tamanho])
        for inicio in range(0, len(palavras), passo)
        if palavras[inicio:inicio + tamanho]
    ]


