def exportar_conversa(historico):
    """Gera um .txt com a conversa atual para download (formato 'messages')."""
    if not historico:
        return None

    linhas = [f"Conversa exportada em {datetime.datetime.now():%d/%m/%Y %H:%M}", "=" * 40, ""]
    for mensagem in historico:
        papel = "Pergunta" if mensagem.get("role") == "user" else "Resposta"
        linhas.append(f"{papel}: {mensagem.get('content', '')}")
        if mensagem.get("role") != "user":
            linhas.append("-" * 40)

    caminho = EXPORTS_DIR / f"conversa_{datetime.datetime.now():%Y%m%d_%H%M%S}.txt"
    caminho.write_text("\n".join(linhas), encoding="utf-8")
    return str(caminho)


